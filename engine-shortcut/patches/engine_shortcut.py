"""engine-shortcut: SHUFFLE + a trigger key opens the settings page of the engine that
voice runs, without playing the voice (M4, on the platform's voice map)."""
import os

TARGET = 'v1.3.0'
SUMMARY = 'Engine shortcut: SHUFFLE + trigger key opens that voice\'s engine settings page'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_M4 = os.path.join(MOD, 'src', 'm4')


def apply(p, arg=None):
    from perkons import m4host

    def pages_header():
        from perkons.voicemap import MAX_ENGINE, numbered
        extra = numbered(p)
        pages = ', '.join(f'PK_PAGE_{extra[e + 1][1]["page"].upper()}'
                          if e + 1 in extra and extra[e + 1][1].get('page') else '0'
                          for e in range(MAX_ENGINE))
        return ('/* generated by engine-shortcut/patches/engine_shortcut.py -- do not edit */\n'
                f'#pragma once\n#define PK_ES_PAGES {{{pages}}}     /* engine e (pk_vm_engine): its settings page, 0 none */\n')

    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'engine_shortcut.c')], [SRC_M4], headers={'es_pages.h': pages_header})
    h.replace_word('keys.handler_lit', 'pk_es_key_event', 'SHUFFLE + trigger: the voice\'s engine settings page')
