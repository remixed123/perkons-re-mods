"""voice-break-maker: BREAK MAKER, a drum break played as a running loop locked to the sequencer
(M7), with a configuration page, a generator that writes the track and kit saving (M4). An extra
voice-map engine (the engine page column of its slot). Needs voice_map in the same build. It takes
over the RAM of the stock custom samples (the break lives there): stock ALGO 3 plays its factory
samples while it's installed, and it can't be built with STEP SAMPLER."""
import os

from perkons.patch import PatchError
from perkons.voicemap import SRC_M7 as VOICE_MAP_M7    # pk_ram.h

TARGET = 'v1.3.0'
SUMMARY = 'voice-break-maker: a 1-bar drum break as a running loop, jumps, rolls, pads, generator'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(MOD, 'src', 'm7')
SRC_M4 = os.path.join(MOD, 'src', 'm4')
COMMON = os.path.join(MOD, 'src', 'common')
NAME = 'break_maker'


def apply(p, arg=None):
    """arg: the voice slot (engine number, 5-16) it's installed in; none: the next free one."""
    from perkons import m4host, m7host

    def needs_voice_map():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-break-maker is a voice-map engine: build it together with voice_map')
    p.on_finish(needs_voice_map)        # first: before the hosts' builds (finishers run in order)
    vm = p.shared.setdefault('voice_map', {'engines': {}})
    if NAME in vm['engines']:
        raise PatchError(f'voice-map engine name {NAME} already taken')
    vm['engines'][NAME] = {'sources': [os.path.join(SRC, 'break_maker.c')],
                           'include_dirs': [SRC, COMMON, VOICE_MAP_M7],
                           'build': 'pk_bm_build', 'slot': int(arg) if arg else None, 'page': 'break_maker'}
    # M7: each step of a BREAK MAKER track, and each voice's page settings, in order with the triggers
    m7host.host(p).message('break-maker-step', 'pk_bm_on_step', ordered=True)
    m7host.host(p).message('break-maker', 'pk_bm_on_settings', ordered=True)
    p.ram_takeover('store', 'default custom samples', 'voice-break-maker')

    def engine_header():
        from perkons.voicemap import numbered
        slot = next(k for k, (n, _) in numbered(p).items() if n == NAME)
        return ('/* generated by voice-break-maker/patches/voice_break_maker.py -- do not edit */\n'
                f'#pragma once\n#define PK_BM_ENGINE {slot - 1}     /* voice-map engine {slot}: the nibble value */\n')

    # M4: the break from the card, the steps, the page, the generator, each kit's settings (BMKR)
    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'break_maker_m4.c')], [SRC_M4, COMMON],
          init='pk_bm_init', headers={'pk_bm_engine.h': engine_header})
    for site in ('boot_init.call_load_samples', 'switch_bank.call_load_samples',
                 'boot_load_last_bank.call_load_samples'):
        h.redirect_call(site, 'pk_bm_load_samples', 'bank load: the stock custom samples left out (the break lives there)')
    for site in ('break_maker.send_triggers.08101e28', 'break_maker.send_triggers.08102ad0'):
        h.redirect_branch(site, 'pk_bm_send_triggers', 'triggers: each BREAK MAKER step first')
    h.store('kit', 'BMKR', 'pk_bm_kit_save', 'pk_bm_kit_restore')
    for site in sorted(k for k in p.symbols['m4'].sites if k.startswith('kits.load.')):
        if p.symbols['m4'].site(site).get('branch'):
            h.redirect_branch(site, 'pk_bm_kit_load', 'kit load: BREAK MAKER settings')
        else:
            h.redirect_call(site, 'pk_bm_kit_load', 'kit load: BREAK MAKER settings')
    h.redirect_call('main.call_switch_done', 'pk_bm_main_loop', 'main loop: the break loading, page sends')
    h.replace_word('keys.handler_lit', 'pk_bm_key_event', 'steps + SHUFFLE on a BREAK MAKER track: its page, for those steps')
    h.page('break_maker', key='pk_bm_page_key', draw='pk_bm_page_draw', enter='pk_bm_page_enter',
           leave='pk_bm_page_leave')
