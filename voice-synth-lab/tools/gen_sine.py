"""Writes src/m7/sl_sine.h: one cycle of a sine in 1024 steps (and the first again, for the
interpolation), read with linear interpolation by the fold and the sine wave. The error is
below -106 dB. Pure Python.

    python3 tools/gen_sine.py
"""
import math
import os

N = 1024
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'm7', 'sl_sine.h')

vals = [math.sin(2 * math.pi * i / N) for i in range(N + 1)]
lines = ['/* generated by tools/gen_sine.py -- do not edit */', '#pragma once', '',
         f'#define SINE_N      {N}', '',
         'static const float SINE[SINE_N + 1] = {']
for i in range(0, N + 1, 8):
    lines.append('    ' + ' '.join(f'{v:.8f}f,' for v in vals[i:i + 8]))
lines.append('};')
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
