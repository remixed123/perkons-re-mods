"""Writes src/m7/sl_minblep.h: the minimum-phase band-limited step (minBLEP) residuals the
oscillators add at each jump (a saw's wrap, a pulse's edges, a hard-sync reset).

A Blackman-windowed sinc, 16 samples long, cut a little below half the sample rate, is made
minimum phase (real cepstrum), integrated into a step, and the ideal step subtracted. Row r,
tap k: the residual k samples after a sample that comes r / PHASES of a sample after the
jump. Pure Python, no numpy.

    python3 tools/gen_minblep.py
"""
import cmath
import math
import os

TAPS, PHASES, CUT = 16, 64, 0.9
N = 8192                                    # FFT size (zero-padded)


def fft(a, inv=False):
    n = len(a)
    if n == 1:
        return a[:]
    ev, od = fft(a[0::2], inv), fft(a[1::2], inv)
    s = 1 if inv else -1
    t = [cmath.exp(s * 2j * math.pi * k / n) * od[k] for k in range(n // 2)]
    return [ev[k] + t[k] for k in range(n // 2)] + [ev[k] - t[k] for k in range(n // 2)]


def ifft(a):
    return [v / len(a) for v in fft(a, True)]


def main():
    m = TAPS * PHASES
    h = []
    for i in range(m + 1):
        x = (i - m / 2) / PHASES                    # in samples, centred
        w = 0.42 - 0.5 * math.cos(2 * math.pi * i / m) + 0.08 * math.cos(4 * math.pi * i / m)
        s = 1.0 if x == 0 else math.sin(math.pi * CUT * x) / (math.pi * CUT * x)
        h.append(w * s)
    # real cepstrum -> minimum phase
    spec = fft([complex(v) for v in h] + [0j] * (N - len(h)))
    cep = ifft([complex(math.log(max(abs(v), 1e-12))) for v in spec])
    fold = [cep[0]] + [2 * cep[i] for i in range(1, N // 2)] + [cep[N // 2]] + [0j] * (N // 2 - 1)
    hmin = [v.real for v in ifft([cmath.exp(v) for v in fft(fold)])]
    # integrate to a step that ends at 1
    step, acc = [], 0.0
    for v in hmin[:m + PHASES]:
        acc += v
        step.append(acc)
    step = [v / acc for v in step]
    rows = []
    for r in range(PHASES + 1):                     # one extra row: linear interpolation
        rows.append([step[min(len(step) - 1, r + k * PHASES)] - 1.0 for k in range(TAPS)])
    rows[-1] = rows[-1][:]
    out = ['/* generated by tools/gen_minblep.py -- do not edit */', '#pragma once', '',
           f'#define MB_TAPS     {TAPS}', f'#define MB_PHASES   {PHASES}', '',
           f'static const float MINBLEP[MB_PHASES + 1][MB_TAPS] = {{']
    for row in rows:
        out.append('    {' + ', '.join(f'{v:.6f}f' for v in row) + '},')
    out += ['};', '']
    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, '..', 'src', 'm7', 'sl_minblep.h'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
