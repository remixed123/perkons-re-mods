"""voice-synth-lab: a mono synth voice (M7): three oscillators with hard sync, a wavefolder, a
filter with its own envelope, eight LFOs; with a configuration page of its own (M4: a long press on
its step on the engine page), Random, Tweak and Mutate. An extra voice-map engine (the engine
page column of its slot). Needs voice_map in the same build. Hook sites in
../symbols/<version>-m4.json."""
import os

from perkons.patch import PatchError
from perkons.voicemap import SRC_M7 as VOICE_MAP_M7    # pk_ram.h

TARGET = 'v1.3.0'
SUMMARY = 'voice-synth-lab mono synth voice for voice-map: 3 oscillators, hard sync, fold, 16 presets'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(MOD, 'src', 'm7')
SRC_M4 = os.path.join(MOD, 'src', 'm4')
COMMON = os.path.join(MOD, 'src', 'common')
NAME = 'synth_lab'


def apply(p, arg=None):
    """arg: the voice slot (engine number, 5-16) it's installed in; none: the next free one."""
    from perkons import m4host, m7host

    def needs_voice_map():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-synth-lab is a voice-map engine: build it together with voice_map')
    p.on_finish(needs_voice_map)        # first: before the hosts' builds (finishers run in order)
    vm = p.shared.setdefault('voice_map', {'engines': {}})
    if NAME in vm['engines']:
        raise PatchError(f'voice-map engine name {NAME} already taken')
    vm['engines'][NAME] = {'sources': [os.path.join(SRC, 'synth_lab.c')],
                           'include_dirs': [SRC, COMMON, VOICE_MAP_M7],
                           'build': 'pk_sy_build', 'slot': int(arg) if arg else None, 'page': 'synth_lab'}
    # M7: a voice's sound, in order with the triggers
    m7host.host(p).message('synth-lab', 'pk_sy_on_sound', ordered=True)
    # M7: the tempo (LFO sync) and each output's DRIVE (the level)
    m7host.host(p).message('synth-lab-live', 'pk_sy_on_live', ordered=True)

    def engine_header():
        from perkons.voicemap import numbered
        slot = next(k for k, (n, _) in numbered(p).items() if n == NAME)
        return ('/* generated by voice-synth-lab/patches/voice_synth_lab.py -- do not edit */\n'
                f'#pragma once\n#define PK_SY_ENGINE {slot - 1}     /* voice-map engine {slot}: the nibble value */\n')

    # M4: each kit's sounds (kit sidecar record SLAB), the page, tempo and DRIVE, the LFO knobs
    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'synth_lab_m4.c')], [SRC_M4, COMMON],
          headers={'pk_sy_engine.h': engine_header})
    h.store('kit', 'SLAB', 'pk_sy_kit_save', 'pk_sy_kit_restore')
    for site in sorted(k for k in p.symbols['m4'].sites if k.startswith('kits.load.')):
        if p.symbols['m4'].site(site).get('branch'):
            h.redirect_branch(site, 'pk_sy_kit_load', 'kit load: Synth Lab sounds')
        else:
            h.redirect_call(site, 'pk_sy_kit_load', 'kit load: Synth Lab sounds')
    h.redirect_call('main.call_switch_done', 'pk_sy_main_loop', 'main loop: Synth Lab PARAM2, tempo, DRIVE')
    for knob in ('rate', 'wave', 'level'):                  # first in the chain: a held cell takes them
        site = next(k for k in p.symbols['m4'].sites if k.startswith(f'synthlab.{knob}.'))
        h.redirect_call(site, f'pk_sy_{knob}', f'LFO {knob} knob: a held Synth Lab cell', order=-1)
    h.page('synth_lab', key='pk_sy_page_key', draw='pk_sy_page_draw', enter='pk_sy_page_enter',
           leave='pk_sy_page_leave')
