"""voice-kick-lab: a kick drum synth voice (M7), with a settings page of its own (a long
press on its step on the engine page). An extra voice-map engine (the engine page column of its
slot). Needs voice_map in the same build."""
import os

from perkons.patch import PatchError

TARGET = 'v1.3.0'
SUMMARY = 'voice-kick-lab kick drum synth voice for voice-map: 16 presets, delay, drive'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(MOD, 'src', 'm7')
SRC_M4 = os.path.join(MOD, 'src', 'm4')
NAME = 'kick_lab'


def apply(p, arg=None):
    """arg: the voice slot (engine number, 5-16) it's installed in; none: the next free one."""
    from perkons import m4host, m7host

    def needs_voice_map():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-kick-lab is a voice-map engine: build it together with voice_map')
    p.on_finish(needs_voice_map)        # first: before the hosts' builds (finishers run in order)
    vm = p.shared.setdefault('voice_map', {'engines': {}})
    if NAME in vm['engines']:
        raise PatchError(f'voice-map engine name {NAME} already taken')
    vm['engines'][NAME] = {'sources': [os.path.join(SRC, 'kick_lab.c')], 'include_dirs': [SRC],
                           'build': 'pk_kl_build', 'slot': int(arg) if arg else None, 'page': 'kick_lab'}
    # M7: each voice's settings (preset, page, PARAM2's values), in order with the triggers
    m7host.host(p).message('kick-lab', 'pk_kl_on_settings', ordered=True)
    # M7: the tempo, for the delay's sync
    m7host.host(p).message('kick-lab-tempo', 'pk_kl_on_tempo', ordered=True)

    def engine_header():
        from perkons.voicemap import numbered
        slot = next(k for k, (n, _) in numbered(p).items() if n == NAME)
        return ('/* generated by voice-kick-lab/patches/voice_kick_lab.py -- do not edit */\n'
                f'#pragma once\n#define PK_KL_ENGINE {slot - 1}     /* voice-map engine {slot}: the nibble value */\n')

    # M4: each kit's settings (kit sidecar record KLAB), the settings page, the tempo
    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'kick_lab_m4.c')], [SRC_M4],
          headers={'pk_kl_engine.h': engine_header})
    h.store('kit', 'KLAB', 'pk_kl_kit_save', 'pk_kl_kit_restore')
    for site in sorted(k for k in p.symbols['m4'].sites if k.startswith('kits.load.')):
        if p.symbols['m4'].site(site).get('branch'):
            h.redirect_branch(site, 'pk_kl_kit_load', 'kit load: Kick Lab settings')
        else:
            h.redirect_call(site, 'pk_kl_kit_load', 'kit load: Kick Lab settings')
    h.redirect_call('main.call_switch_done', 'pk_kl_main_loop', 'main loop: Kick Lab PARAM2 and tempo')
    h.page('kick_lab', key='pk_kl_page_key', draw='pk_kl_page_draw', enter='pk_kl_page_enter',
           leave='pk_kl_page_leave')
