"""voice-3-oh: an acid bass line voice (M7): saw or square through a diode ladder filter with
accents and slides, four distortions; with a configuration page of its own (M4: a long press on
its step on the engine page) and Random. An extra voice-map engine (the engine page column of
its slot). Needs voice_map in the same build."""
import os

from perkons.patch import PatchError
from perkons.voicemap import SRC_M7 as VOICE_MAP_M7    # pk_ram.h

TARGET = 'v1.3.0'
SUMMARY = 'voice-3-oh acid bass voice for voice-map: diode ladder filter, accent, slide, 4 distortions, 16 presets'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(MOD, 'src', 'm7')
SRC_M4 = os.path.join(MOD, 'src', 'm4')
COMMON = os.path.join(MOD, 'src', 'common')
NAME = 'three_oh'


def apply(p, arg=None):
    """arg: the voice slot (engine number, 5-16) it's installed in; none: the next free one."""
    from perkons import m4host, m7host

    def needs_voice_map():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-3-oh is a voice-map engine: build it together with voice_map')
    p.on_finish(needs_voice_map)        # first: before the hosts' builds (finishers run in order)
    vm = p.shared.setdefault('voice_map', {'engines': {}})
    if NAME in vm['engines']:
        raise PatchError(f'voice-map engine name {NAME} already taken')
    vm['engines'][NAME] = {'sources': [os.path.join(SRC, 'three_oh.c')],
                           'include_dirs': [SRC, COMMON, VOICE_MAP_M7],
                           'build': 'pk_oh_build', 'slot': int(arg) if arg else None, 'page': 'three_oh'}
    # M7: a voice's sound, in order with the triggers
    m7host.host(p).message('three-oh', 'pk_oh_on_sound', ordered=True)
    # M7: the tempo (the gate length) and each output's DRIVE (the level)
    m7host.host(p).message('three-oh-live', 'pk_oh_on_live', ordered=True)

    def engine_header():
        from perkons.voicemap import numbered
        slot = next(k for k, (n, _) in numbered(p).items() if n == NAME)
        return ('/* generated by voice-3-oh/patches/voice_3_oh.py -- do not edit */\n'
                f'#pragma once\n#define PK_OH_ENGINE {slot - 1}     /* voice-map engine {slot}: the nibble value */\n')

    # M4: each kit's sounds (kit sidecar record 3OHS), the page, tempo and DRIVE
    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'three_oh_m4.c')], [SRC_M4, COMMON],
          headers={'pk_oh_engine.h': engine_header})
    h.store('kit', '3OHS', 'pk_oh_kit_save', 'pk_oh_kit_restore')
    for site in sorted(k for k in p.symbols['m4'].sites if k.startswith('kits.load.')):
        if p.symbols['m4'].site(site).get('branch'):
            h.redirect_branch(site, 'pk_oh_kit_load', 'kit load: 3 Oh sounds')
        else:
            h.redirect_call(site, 'pk_oh_kit_load', 'kit load: 3 Oh sounds')
    h.redirect_call('main.call_switch_done', 'pk_oh_main_loop', 'main loop: 3 Oh PARAM2, tempo, DRIVE')
    h.page('three_oh', key='pk_oh_page_key', draw='pk_oh_page_draw', enter='pk_oh_page_enter',
           leave='pk_oh_page_leave')
